import { createRequire } from 'node:module';
import html5 from 'html-validate/elements/html5';

const require = createRequire(import.meta.url);
const htmlValidatePackage = require('html-validate/package.json');

export const GENERATED_METADATA_PATH = 'lib/generated/html5-attributes.js';
export const HTML_ATTRIBUTE_METADATA_SOURCE = `html-validate@${htmlValidatePackage.version}`;

function normalizeAttribute(attribute) {
  return attribute.toLowerCase();
}

function staticValues(definition) {
  if (!Array.isArray(definition.enum)) {
    return null;
  }

  const values = definition.enum.filter((value) => !/^\/.*\/$/u.test(value));
  return values.length > 0 ? values : null;
}

function attributesFor(element) {
  return Object.fromEntries(
    Object.entries(element.attributes ?? {}).map(([name, definition]) => [
      normalizeAttribute(name),
      staticValues(definition),
    ]),
  );
}

export function getHtmlAttributeMetadata() {
  const elements = Object.fromEntries(
    Object.entries(html5)
      .filter(([name]) => name !== '*')
      .map(([name, definition]) => [name, attributesFor(definition)]),
  );
  const globalAttributes = attributesFor(html5['*']);

  return { elements, globalAttributes };
}

export function renderHtmlAttributeMetadata() {
  const metadata = getHtmlAttributeMetadata();
  return `// Generated by scripts/generate-html-attribute-metadata.mjs from ${HTML_ATTRIBUTE_METADATA_SOURCE}.\n// Do not edit by hand. Update the exact dev dependency, regenerate, inspect this diff, and run yarn quality:complete.\n\nexport const HTML5_METADATA_SOURCE = '${HTML_ATTRIBUTE_METADATA_SOURCE}';\nexport const HTML5_GLOBAL_ATTRIBUTES = ${JSON.stringify(metadata.globalAttributes, null, 2)};\nexport const HTML5_ELEMENT_ATTRIBUTES = ${JSON.stringify(metadata.elements, null, 2)};\n`;
}
